import '../../../../domain/entities/entities.dart';

// Reward Details model (will call in details_data_model.dart)

class DetailsModel extends DetailsEntity {
  const DetailsModel({
    required super.id,
    super.image,
    super.type,
    super.name,
    super.desc,
    super.code,
    super.redeem,
    super.frequency,
    super.quantity,
    super.period,
    super.start,
    super.end,
    super.isMuslim,
    super.muslimCategory,
    super.points,
    super.credits,
    super.purchaseMethod,
    super.convertRate,
    super.faceAmount,
    super.isFavourite,
    super.isDiscount,
    super.aftDisPoints,
    super.aftDisCredits,
    super.aftDisCoins,
    super.tnc,
    super.purchaseText,
    super.voucherType,
    super.isSoldOut,
    super.totalRedeemed,
    super.totalOwned,
    super.isAbleRedeem,
    super.share,
    super.shareLink,

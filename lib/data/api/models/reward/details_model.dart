      image: json['image'] ?? '',
      type: json['type'] ?? '',
      name: json['name'] ?? '',
      desc: json['desc'] ?? '',
      code: json['code'] ?? '',
      redeem: json['redeem'],
      frequency: json['frequency'] ?? '',
      quantity: json['quantity'],
      period: json['period'] ?? '',
      start: json['start'] ?? '',
      end: json['end'] ?? '',
      isMuslim: json['isMuslim'],
      muslimCategory: json['muslimCategory'] ?? '',
      points: json['points'] ?? '',
      credits: json['credits'] ?? '',
      purchaseMethod: json['purchaseMethod'],
      convertRate: json['convertRate'],
      faceAmount: json['faceAmount'] ?? '',
      isFavourite: json['isFavourite'] ?? false,
      isDiscount: json['isDiscount'],
      aftDisPoints: json['aftDisPoints'] ?? '',
      aftDisCredits: json['aftDisCredits'] ?? '',
      aftDisCoins: json['aftDisCoins'] ?? '',
      tnc: json['tnc'] ?? '',
      purchaseText: json['purchaseText'],
      voucherType: json['voucherType'],
      isSoldOut: json['isSoldOut'] ?? false,
      totalRedeemed: json['totalRedeemed'] ?? '',
      totalOwned: json['totalOwned'] ?? '',
      isAbleRedeem: json['isAbleRedeem'] ?? false,
      share: json['share'] ?? '',
      shareLink: json['share_link'] ?? '',
    );
  }
}
